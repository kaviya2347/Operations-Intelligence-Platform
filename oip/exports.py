"""Exports: Power BI (star-schema CSVs + generated DAX + model notes) and the offline web snapshot.

export_powerbi()  -> ./powerbi/   load the CSVs in Power BI Desktop, paste measures.dax, follow MODEL.md
export_static()   -> ./web/static/snapshot.js   the dashboard runs from this file when no API is reachable
"""
from __future__ import annotations

import json
import time

from oip import artifacts, config, db
from oip.reference import QUEUES

PBI_TABLES = {
    "dim_date": "SELECT * FROM dim_date",
    "dim_interval": "SELECT * FROM dim_interval",
    "dim_client": "SELECT * FROM dim_client",
    "dim_queue": "SELECT * FROM dim_queue",
    "dim_team_leader": "SELECT * FROM dim_team_leader",
    "dim_agent": "SELECT agent_id, agent_login, full_name, site, team_leader_id, queue_id, shift, date_of_joining, tenure_band FROM dim_agent",
    "rpt_interval_cube": "SELECT * FROM rpt_interval_cube",
    "rpt_agent_day": "SELECT * FROM rpt_agent_day",
}

MODEL_MD = """# Power BI model notes

Generated by `python -m oip export-powerbi` on {built}. Numbers in these files match the dashboard and the SQL lab exactly:
every ratio is exported as an additive numerator and denominator, and the measures divide sums.

## Load

1. Get data → Text/CSV for each file in this folder. Keep column types as detected; set `date` in `dim_date` to Date.
2. Model view → mark `dim_date` as the date table (Table tools → Mark as date table → `date`).
3. Create the relationships below (single direction, dimension filters fact).
4. New measure → paste each block from `measures.dax`.

## Relationships

| From (many) | To (one) | Key |
|---|---|---|
| rpt_interval_cube | dim_date | date_key |
| rpt_interval_cube | dim_interval | interval_idx |
| rpt_interval_cube | dim_queue | queue_id |
| rpt_agent_day | dim_date | date_key |
| rpt_agent_day | dim_queue | queue_id |
| rpt_agent_day | dim_agent | agent_id |
| dim_queue | dim_client | client_id |
| dim_agent | dim_team_leader | team_leader_id |

The cube's grain is queue × date × 30-minute interval. Do not join interaction-level facts to `fact_case_status` without
first keeping the latest status per case (one interaction has many statuses).

## Row-level security

Modeling → Manage roles. One role per access level, filtering `dim_queue`:

| Role | Table filter on dim_queue |
|---|---|
| Admin, Analyst | none |
| Team leader, Billing | `[queue_id] = "Q01"` |
| Client viewer, Meridian | `[queue_id] IN {{"Q04", "Q09"}}` |

For client viewers also hide `dim_agent[full_name]` (object-level security) or publish a version without it.

## Pages (as built during the internship)

Queue performance: KPI cards (Offered, Service level, Abandon rate, AHT, FCR, CSAT), daily trend with target line,
queue × metric matrix with conditional formatting against each queue's own target; slicers for date, queue and shift
synced across pages.

## Metrics

{metrics}
"""


def export_powerbi(out=None, with_facts: bool = False):
    from oip.warehouse.metrics import METRICS, dax_measures
    out = out or config.POWERBI_DIR
    out.mkdir(parents=True, exist_ok=True)
    tables = dict(PBI_TABLES)
    if with_facts:
        tables["fact_interaction"] = ("SELECT interaction_id, date_key, interval_idx, queue_id, client_id, agent_id, channel, offered, handled, "
                                      "abandoned, short_abandon, within_sl, talk_sec, hold_sec, acw_sec, handle_sec, fcr, fcr_eligible FROM fact_interaction")
    for name, sql in tables.items():
        df = db.read_sql(sql)
        df.to_csv(out / f"{name}.csv", index=False)
        print(f"  [powerbi] {name}.csv  {len(df):,} rows", flush=True)
    (out / "measures.dax").write_text(dax_measures())
    mt = "\n".join(f"- **{m.label}**: {m.definition} Numerator: {m.numerator}. Denominator: {m.denominator}. Exclusions: {m.exclusions}." for m in METRICS)
    (out / "MODEL.md").write_text(MODEL_MD.format(built=time.strftime("%Y-%m-%d %H:%M"), metrics=mt))
    print(f"  [powerbi] measures.dax, MODEL.md -> {out}", flush=True)
    return out


def _round_vec(v, d=3):
    return [round(float(x), d) for x in v]


def build_snapshot() -> dict:
    """Call the real API in-process for every payload the dashboard needs, so the snapshot cannot drift from it."""
    from fastapi.testclient import TestClient
    from oip.api.app import app
    from oip.api.sql_lab import SAVED
    from oip.copilot import answer as A
    from oip.copilot.documents import ABBREVIATIONS
    from oip.copilot.index import STOP, get_index

    c = TestClient(app)

    def get(path, user="ops-admin"):
        r = c.get("/api/" + path, headers={"X-OIP-User": user})
        r.raise_for_status()
        return r.json()

    users = get("users")
    snap = {"version": 1, "built_at": time.strftime("%Y-%m-%d %H:%M:%S"), "users": users,
            "meta": {u["id"]: get("meta", u["id"]) for u in users}}
    for m in snap["meta"].values():
        m["llm"] = {"provider": "extractive", "model": "none (quotes sources)", "configured": "snapshot"}
    snap["cube"] = get("cube")
    snap["agents"] = get("agents")
    snap["rca"] = {q.queue_id: get(f"rca?queue={q.queue_id}") for q in QUEUES if q.realtime}
    snap["forecast"] = get("forecast")
    snap["alerts"] = get("alerts")
    snap["quality"] = get("quality")
    snap["eda"] = get("eda")
    snap["catalog"] = get("catalog")
    idx = get_index()
    snap["copilot"] = {"docs": get("copilot/docs"), "chunks": get("copilot/chunks"), "eval": get("copilot/eval"),
                       "vectors": [_round_vec(v) for v in idx.vectors], "abbreviations": ABBREVIATIONS, "stopwords": sorted(STOP),
                       "system": A.SYSTEM, "action_sections": list(A.ACTION_SECTIONS), "action_q": A.ACTION_Q.pattern,
                       "imperatives": A.IMPERATIVES}
    results = {}
    for s in SAVED:
        r = c.post("/api/sql", json={"sql": s["sql"]}, headers={"X-OIP-User": "ops-admin"}).json()
        if "rows" in r:
            r["rows"] = r["rows"][:300]
        results[s["id"]] = r
    snap["sql"] = {"saved": SAVED, "results": results}
    return snap


def export_static(out=None):
    out = out or (config.WEB_DIR / "static" / "snapshot.js")
    out.parent.mkdir(parents=True, exist_ok=True)
    snap = build_snapshot()
    body = artifacts.dumps(snap) if hasattr(artifacts, "dumps") else json.dumps(snap)
    out.write_text("/* Generated by python -m oip export-static. Offline data for the dashboard. */\nwindow.OIP_SNAPSHOT = " + body + ";\n")
    print(f"  [static] {out}  {out.stat().st_size / 1e6:.1f} MB", flush=True)
    return out
